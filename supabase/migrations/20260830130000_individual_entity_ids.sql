-- Every individual gets its register identifier (the individuals/ecotype slice of
-- salish-ox2.5, sequenced by decision 034's "individuals and ecotypes now").
--
-- The register (salish-sea/animals) is the source of individual identity under animals
-- ADR-0012, recorded on our side by decision 033. The reconciliation
-- (docs/reference/register-reconciliation.md, edition 2026.08.1) resolved every one of
-- the 510 individuals to exactly one register entity, so nothing here is a judgment
-- call: the pairs below are that measurement, committed as data/individual-entities.tsv
-- and embedded here because a migration must be static.
--
-- What this column is FOR: decision 034 keys profile URLs on it — /individuals/0010193/
-- T065A instead of /individuals/T065A, which today dies for all 65 non-primary
-- designations. The identifier is opaque and permanent (animals ADR-0002, ADR-0010),
-- which is what a public URL needs and what primary_designation is not:
-- designations.superseded_by exists precisely because codes get replaced.
--
-- UNIQUE is load-bearing, not hygiene. The reconciliation's sharpest finding was six
-- register entities each claimed by TWO catalogue rows; a future assignment that hands
-- two rows one SSA: must fail here rather than ship. (The six were group rows, retired
-- in 20260830120000 — but the constraint is what makes the hazard structural rather
-- than remembered.)
--
-- social_groups gains the same column but only the ecotype is populated. The matrilines
-- stay NULL deliberately: 73 of our 132 have no register entity at all (animals Q22,
-- salish-ox2.6), and guessing the other 59 now would key pages on a tier the register
-- itself calls its least confident. They fill in when Q22 answers.
--
-- Additive: no view reads these columns yet; grants are table-level and cover new
-- columns; the DwC-A build reads neither table.

ALTER TABLE public.individuals ADD COLUMN entity_id TEXT UNIQUE;
COMMENT ON COLUMN public.individuals.entity_id IS
  'The register''s permanent identifier for this animal (salish-sea/animals, ADR-0002/'
  '0010). Key URLs and presentation overrides on this, never on a designation — '
  'designations are labels and labels get replaced. Populated from '
  'data/individual-entities.tsv; a row this mapping misses fails the migration.';

ALTER TABLE public.social_groups ADD COLUMN entity_id TEXT UNIQUE;
COMMENT ON COLUMN public.social_groups.entity_id IS
  'The register''s permanent identifier. Populated for the ecotype only; matrilines are '
  'deliberately NULL until animals Q22 settles which lineage levels are real '
  '(salish-ox2.6). UNIQUE so no two rows can ever claim one register entity.';

